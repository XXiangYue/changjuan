"""数据模型定义"""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional, List, Callable


@dataclass
class InitDoc:
    """初始化文档"""
    name: str                           # 文档名称
    path: str                           # 文档路径（相对于 workspace）
    prompt: str                          # 填写指导提示词
    status: str = "待生成"              # 状态
    content: str = ""                   # 生成的内容


@dataclass
class MemoryDocTemplate:
    """记忆文档模板"""
    name: str           # 文档名称
    path: str           # 文档路径
    update_rules: str   # 更新规则描述


@dataclass
class ChapterInfo:
    """章节信息"""
    volume_num: int      # 卷编号
    chapter_num: int     # 章节编号
    file_path: Path      # 章节文件路径


@dataclass
class VolumeInfo:
    """卷信息"""
    volume_num: int      # 卷编号
    volume_dir: Path     # 卷文件夹路径
    chapter_count: int   # 已有章节数


@dataclass
class WorkflowConfig:
    """工作流配置"""
    output_callback: Callable[[str], None]
    agent = None  # Agent 实例，稍后设置

    @property
    def work_dir(self) -> Optional[Path]:
        return self._work_dir

    @work_dir.setter
    def work_dir(self, value: Path):
        self._work_dir = value

    @property
    def novel_dir(self) -> Optional[Path]:
        return self._novel_dir

    @novel_dir.setter
    def novel_dir(self, value: Path):
        self._novel_dir = value

    @property
    def workspace_dir(self) -> Optional[Path]:
        return self._workspace_dir

    @workspace_dir.setter
    def workspace_dir(self, value: Path):
        self._workspace_dir = value


